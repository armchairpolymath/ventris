"""Read Prusa binary G-code (.bgcode) into plain text.

Pure-Python port of the parts of Prusa's libbgcode needed for reading
(https://github.com/prusa3d/libbgcode, doc/specifications.md):
blocks, CRC32 checks, Deflate / Heatshrink decompression and MeatPack decoding.
"""

from __future__ import annotations

import re
import struct
import zlib
from dataclasses import dataclass, field

MAGIC = b"GCDE"

BLOCK_FILE_META, BLOCK_GCODE, BLOCK_SLICER_META, BLOCK_PRINTER_META, \
    BLOCK_PRINT_META, BLOCK_THUMBNAIL = range(6)
_PARAM_SIZE = {BLOCK_THUMBNAIL: 6}  # every other block type has 2 bytes of params
_THUMB_FORMATS = {0: "PNG", 1: "JPG", 2: "QOI"}
_EMPTY_COMMENT = re.compile(r"^;[ \t]*\n", re.M)


class BgcodeError(Exception):
    pass


@dataclass
class BgcodeDocument:
    gcode: str
    file_metadata: dict[str, str] = field(default_factory=dict)
    printer_metadata: dict[str, str] = field(default_factory=dict)
    print_metadata: dict[str, str] = field(default_factory=dict)
    slicer_metadata: dict[str, str] = field(default_factory=dict)
    thumbnails: list[tuple[str, int, int]] = field(default_factory=list)

    def to_text(self) -> str:
        """Lay the file out like PrusaSlicer's plain-text G-code."""
        out = []
        producer = self.file_metadata.get("Producer")
        if producer:
            out.append(f"; generated by {producer}")
            out.append("")
        out += [f"; {k} = {v}" for k, v in self.printer_metadata.items()]
        out.append("")
        for fmt, w, h in self.thumbnails:
            out.append(f"; thumbnail_{fmt} {w}x{h} (preview image, not shown)")
        if self.thumbnails:
            out.append("")
        body = "\n".join(out) + "\n" + self.gcode
        if not body.endswith("\n"):
            body += "\n"
        tail = [f"; {k} = {v}" for k, v in self.print_metadata.items()]
        tail.append("")
        tail.append("; prusaslicer_config = begin")
        tail += [f"; {k} = {v}" for k, v in self.slicer_metadata.items()]
        tail.append("; prusaslicer_config = end")
        return body + "\n" + "\n".join(tail) + "\n"


def is_bgcode(data: bytes) -> bool:
    return data[:4] == MAGIC


def decode(data: bytes) -> BgcodeDocument:
    if not is_bgcode(data):
        raise BgcodeError("Not a binary G-code file (missing GCDE header).")
    if len(data) < 10:
        raise BgcodeError("File is truncated.")
    version, checksum_type = struct.unpack_from("<IH", data, 4)
    if version != 1:
        raise BgcodeError(f"Unsupported binary G-code version {version}.")
    crc_size = 4 if checksum_type == 1 else 0

    doc = BgcodeDocument(gcode="")
    gcode_parts: list[str] = []
    pos = 10
    while pos < len(data):
        if pos + 8 > len(data):
            raise BgcodeError("File is truncated (block header).")
        block_type, compression, size = struct.unpack_from("<HHI", data, pos)
        header_size = 8
        stored = size
        if compression:
            stored = struct.unpack_from("<I", data, pos + 8)[0]
            header_size = 12
        param_size = _PARAM_SIZE.get(block_type, 2)
        payload_start = pos + header_size
        data_start = payload_start + param_size
        end = data_start + stored
        if end + crc_size > len(data):
            raise BgcodeError("File is truncated (block data).")
        if crc_size:
            expected = struct.unpack_from("<I", data, end)[0]
            if zlib.crc32(data[pos:end]) != expected:
                raise BgcodeError("Checksum mismatch — the file is damaged.")
        params = data[payload_start:data_start]
        raw = _decompress(data[data_start:end], compression, size)

        if block_type == BLOCK_GCODE:
            encoding = struct.unpack("<H", params)[0]
            gcode_parts.append(meatpack_decode(raw) if encoding in (1, 2)
                               else raw.decode("utf-8", "replace"))
        elif block_type == BLOCK_THUMBNAIL:
            fmt, width, height = struct.unpack("<HHH", params)
            doc.thumbnails.append((_THUMB_FORMATS.get(fmt, "?"), width, height))
        elif block_type in (BLOCK_FILE_META, BLOCK_PRINTER_META, BLOCK_PRINT_META,
                            BLOCK_SLICER_META):
            target = {BLOCK_FILE_META: doc.file_metadata,
                      BLOCK_PRINTER_META: doc.printer_metadata,
                      BLOCK_PRINT_META: doc.print_metadata,
                      BLOCK_SLICER_META: doc.slicer_metadata}[block_type]
            target.update(_parse_ini(raw.decode("utf-8", "replace")))
        pos = end + crc_size

    # PrusaSlicer's text export and libbgcode's converter both drop empty ";" lines
    doc.gcode = _EMPTY_COMMENT.sub("", "".join(gcode_parts))
    return doc


def _decompress(data: bytes, compression: int, size: int) -> bytes:
    if compression == 0:
        return data
    if compression == 1:
        return zlib.decompress(data)
    if compression == 2:
        return heatshrink_decode(data, 11, 4)
    if compression == 3:
        return heatshrink_decode(data, 12, 4)
    raise BgcodeError(f"Unknown compression type {compression}.")


def _parse_ini(text: str) -> dict[str, str]:
    result = {}
    for line in text.splitlines():
        key, sep, value = line.partition("=")
        if sep:
            result[key.strip()] = value.strip()
    return result


# ---------------------------------------------------------------- heatshrink


def heatshrink_decode(data: bytes, window_bits: int, lookahead_bits: int) -> bytes:
    """Decode a heatshrink stream (MSB-first bits; 1 = literal byte, 0 = back-reference)."""
    out = bytearray()
    total = len(data) * 8
    padded = data + b"\x00\x00\x00\x00"
    backref_bits = 1 + window_bits + lookahead_bits
    index_shift = lookahead_bits
    index_mask = (1 << window_bits) - 1
    count_mask = (1 << lookahead_bits) - 1
    from_bytes = int.from_bytes
    pos = 0
    while True:
        byte = pos >> 3
        # 32 bits starting at the current byte; the token sits in the top bits
        word = from_bytes(padded[byte:byte + 4], "big")
        offset = pos & 7
        if (word >> (31 - offset)) & 1:  # literal
            if pos + 9 > total:
                break
            out.append((word >> (23 - offset)) & 0xFF)
            pos += 9
        else:
            if pos + backref_bits > total:
                break
            token = (word >> (32 - offset - backref_bits)) & ((1 << (backref_bits - 1)) - 1)
            distance = ((token >> index_shift) & index_mask) + 1
            count = (token & count_mask) + 1
            start = len(out) - distance
            if start < 0:
                raise BgcodeError("Corrupt compressed data (back-reference before start).")
            if distance >= count:
                out += out[start:start + count]
            else:
                for i in range(count):
                    out.append(out[start + i])
            pos += backref_bits
    return bytes(out)


# ---------------------------------------------------------------- MeatPack

_MP_SIGNAL = 0xFF
_MP_ENABLE, _MP_DISABLE, _MP_RESET, _MP_QUERY, _MP_NOSPACE_ON, _MP_NOSPACE_OFF = \
    251, 250, 249, 248, 247, 246
_MP_CHARS = "0123456789. \nGX"  # index 11 becomes 'E' in no-spaces mode
_GLINE_PARAMS = re.compile(r"(?<=[^ \n])([XYZEFIJRSGPWHCA])")


def meatpack_decode(data: bytes) -> str:
    """Port of libbgcode's MeatPack::unbinarize."""
    out: list[str] = []
    append = out.append
    packing = False
    chars = _MP_CHARS
    full_queue = 0
    char_buf = ""
    signal_count = 0
    cmd_active = False

    for c in data:
        if c == _MP_SIGNAL:
            if signal_count:
                cmd_active = True
                signal_count = 0
            else:
                signal_count = 1
            continue
        if cmd_active:
            if c == _MP_ENABLE:
                packing = True
            elif c in (_MP_DISABLE, _MP_RESET):
                packing = False
            elif c == _MP_NOSPACE_ON:
                chars = _MP_CHARS[:11] + "E" + _MP_CHARS[12:]
            elif c == _MP_NOSPACE_OFF:
                chars = _MP_CHARS
            cmd_active = False
            continue
        pending = [_MP_SIGNAL, c] if signal_count else [c]
        signal_count = 0
        for b in pending:
            if not packing:
                append(chr(b))
            elif full_queue:
                append(chr(b))
                if char_buf:
                    append(char_buf)
                    char_buf = ""
                full_queue -= 1
            else:
                low, high = b & 0xF, b >> 4
                if low == 0xF:
                    full_queue += 1
                    if high == 0xF:
                        full_queue += 1
                    else:
                        char_buf = chars[high]
                else:
                    first = chars[low]
                    append(first)
                    if first != "\n":
                        if high == 0xF:
                            full_queue += 1
                        else:
                            append(chars[high])

    text = re.sub(r"\n{2,}", "\n", "".join(out))
    # libbgcode re-inserts the spaces MeatPack's no-spaces mode removed, on G lines only
    return "\n".join(_GLINE_PARAMS.sub(r" \1", line) if line.startswith("G") else line
                     for line in text.split("\n"))
