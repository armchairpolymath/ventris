import unittest
from pathlib import Path

from ventris.dialects import detect_profile, detection_sample, get_profile, profiles
from ventris.explain import explain
from ventris.parser import parse_line
from ventris.state import MachineState

FIXTURES = Path(__file__).parent / "fixtures"
SAMPLE = (FIXTURES / "kobra3_sample.gcode").read_text()


def ex(text, before=None):
    before = before or MachineState()
    after = MachineState(**vars(before))
    line = parse_line(text)
    after.apply(line)
    return explain(line, before, after, get_profile("kobra"))


class KobraProfileTest(unittest.TestCase):
    def test_registered(self):
        self.assertIn("kobra", [p.key for p in profiles()])

    def test_detects_anycubic_slicer_next_file(self):
        self.assertEqual(detect_profile(detection_sample(SAMPLE)).key, "kobra")

    def test_detects_printer_named_only_at_the_end(self):
        # OrcaSlicer / PrusaSlicer write the printer name in the settings block at
        # the end, past what the header sample covers.
        body = "; generated by PrusaSlicer 2.8.1\nG28\n" + "G1 X1 Y1 E.1\n" * 8000
        text = body + "; printer_settings_id = Anycubic Kobra 2 Pro\n"
        self.assertEqual(detect_profile(detection_sample(text)).key, "kobra")
        self.assertEqual(detect_profile(detection_sample(body)).key, "prusa")

    def test_every_command_in_sample_is_known(self):
        unknown = {parse_line(l).code for l in SAMPLE.splitlines()
                   if parse_line(l).code and ex(l).kind == "unknown"}
        self.assertEqual(unknown, set())

    def test_start_routine(self):
        e = ex("G9111 bedTemp=60 extruderTemp=220")
        self.assertEqual(e.source, "vendor")
        self.assertIn("60 °C", e.sentence)
        self.assertIn("220 °C", e.sentence)
        self.assertIn("wipes the nozzle", e.sentence)

    def test_start_routine_sets_state(self):
        state = MachineState()
        state.apply(parse_line("G9111 bedTemp=60 extruderTemp=220"))
        self.assertTrue(state.homed)
        self.assertEqual((state.bed_target, state.hotend_target), (60, 220))

    def test_progress_with_speed_modes(self):
        sentence = ex("M73 P1 R14 QuietR27 SportR11 ; NormalR866.159s").sentence
        self.assertIn("1% done", sentence)
        self.assertIn("14 minutes", sentence)
        self.assertIn("27 min in quiet mode", sentence)
        state = MachineState()
        state.apply(parse_line("M73 P1 R14 QuietR27 SportR11"))
        self.assertEqual((state.progress, state.remaining_min), (1, 14))

    def test_layer_notices(self):
        self.assertIn("layer 12", ex("M73 L12").sentence)
        e = ex("M991 S0 P11 ;notify layer change")
        self.assertEqual(e.source, "community")
        self.assertIn("layer 12", e.sentence)

    def test_klipper_commands(self):
        self.assertIn("corner speed 9", ex("SET_VELOCITY_LIMIT SQUARE_CORNER_VELOCITY=9").sentence)
        self.assertIn("acceleration 10000",
                      ex("SET_VELOCITY_LIMIT VELOCITY=350 ACCEL=10000").sentence)
        self.assertIn("cube_id_0", ex("EXCLUDE_OBJECT_START NAME=cube_id_0").sentence)

    def test_marlin_kobra_commands(self):
        self.assertIn("light on", ex("M355 S1").sentence)
        self.assertIn("saved", ex("M420 S1").sentence)
        self.assertEqual(ex("G29").kind, "command")
        self.assertIn("Clear", ex("M117").sentence)

    def test_filament_slot_and_flush_block(self):
        self.assertIn("slot 3", ex("T2").sentence)
        self.assertEqual(ex(";;; G1 X261 Y25 F12000").title, "Disabled command (filament swap)")
        self.assertEqual(ex("; FLUSH_START").title, "Filament swap starts")

    def test_fans(self):
        self.assertIn("chamber fan", ex("M106 P3 S153").sentence)

    def test_comment_markers(self):
        self.assertEqual(ex("; AFTER_LAYER_CHANGE 0 @ 0.2mm").title, "After layer change")
        self.assertIn("outside", ex(";TYPE:Outer wall").sentence.lower())
        self.assertIn("outside", ex(";TYPE:External perimeter").sentence.lower())
        self.assertEqual(ex("; layer num/total_layer_count: 5/120").title, "Layer 5 of 120")
        self.assertEqual(ex('; printing object "Cube" id:0 copy 0').title, "Object: Cube")

    def test_stray_text_is_not_blank(self):
        # Some Kobra 2 profiles write "[layer_num] @ [layer_z]mm" without a semicolon.
        self.assertEqual(ex("5 @ 1.0mm").kind, "unknown")


if __name__ == "__main__":
    unittest.main()
