import unittest
from pathlib import Path

from ventris.dialects import detect_profile, detection_sample, get_profile, profiles
from ventris.explain import explain
from ventris.parser import parse_line
from ventris.state import MachineState

FIXTURES = Path(__file__).parent / "fixtures"
SAMPLE = (FIXTURES / "qidi_xplus4_sample.gcode").read_text(encoding="utf-8")


def ex(text, before=None):
    before = before or MachineState()
    after = MachineState(**vars(before))
    line = parse_line(text)
    after.apply(line)
    return explain(line, before, after, get_profile("qidi"))


def run(text):
    state = MachineState()
    for line in text.splitlines():
        state.apply(parse_line(line))
    return state


class QidiProfileTest(unittest.TestCase):
    def test_registered(self):
        self.assertIn("qidi", [p.key for p in profiles()])

    def test_detects_qidistudio_file(self):
        self.assertEqual(detect_profile(detection_sample(SAMPLE)).key, "qidi")

    def test_detects_orcaslicer_file_named_at_the_end(self):
        body = "; generated by OrcaSlicer 2.2.0\nPRINT_START BED=60 HOTEND=220\n"
        body += "G1 X1 Y1 E.1\n" * 8000
        text = body + "; printer_settings_id = Qidi Q1 Pro 0.4 nozzle\n"
        self.assertEqual(detect_profile(detection_sample(text)).key, "qidi")

    def test_qidi_m1002_is_not_bambu(self):
        # Bambu and QIDI both use M1002, for different things.
        self.assertEqual(detect_profile("SET_PRINT_MAIN_STATUS MAIN_STATUS=print_start\n"
                                        "M1002 R1\n").key, "qidi")
        self.assertEqual(detect_profile("M1002 gcode_claim_action : 2\n").key, "bambu")

    def test_every_command_in_sample_is_known(self):
        unknown = {parse_line(l).code for l in SAMPLE.splitlines()
                   if parse_line(l).code and ex(l).kind == "unknown"}
        self.assertEqual(unknown, set())

    def test_start_routine(self):
        e = ex("PRINT_START BED=60 HOTEND=220 CHAMBER=45 EXTRUDER=1")
        self.assertEqual(e.source, "vendor")
        self.assertIn("60 °C", e.sentence)
        self.assertIn("220 °C", e.sentence)
        self.assertIn("chamber to 45 °C", e.sentence)
        self.assertIn("filament 2 (T1)", e.sentence)

    def test_start_routine_sets_state(self):
        state = run("PRINT_START BED=60 HOTEND=220 CHAMBER=45 EXTRUDER=0")
        self.assertTrue(state.homed)
        self.assertEqual((state.bed_target, state.hotend_target, state.chamber_target),
                         (60, 220, 45))

    def test_layer_counts(self):
        self.assertIn("layer 3", ex("SET_PRINT_STATS_INFO CURRENT_LAYER=3").sentence)
        state = run("SET_PRINT_STATS_INFO TOTAL_LAYER=120\nSET_PRINT_STATS_INFO CURRENT_LAYER=7")
        self.assertEqual((state.layer, state.total_layers), (7, 120))
        self.assertEqual((run(SAMPLE).layer, run(SAMPLE).total_layers), (2, 2))

    def test_fans_count_from_zero(self):
        self.assertIn("part-cooling", ex("M106 P0 S255").sentence)
        self.assertIn("auxiliary", ex("M106 P2 S128").sentence)
        self.assertIn("chamber fan", ex("M106 P3 S255").sentence)
        self.assertIn("Polar cooler” on", ex("M106 P4 S1").sentence)

    def test_x_max_4_commands(self):
        self.assertIn("saved", ex("M1002 A1").sentence)
        self.assertIn("Clear", ex("M1002 R1").sentence)
        self.assertIn("cooled to 190 °C", ex("M109.1 S190").sentence)
        self.assertIn("“measuring the bed”",
                      ex("SET_PRINT_SUB_STATUS SUB_STATUS=auto_bed_adjust").sentence)
        self.assertEqual(ex("G29.0").source, "vendor")

    def test_nozzle_height_correction(self):
        line = parse_line("G92_ Z9.986")
        self.assertEqual(line.code, "G92_")
        before = run("G28\nG1 X195 Y195 Z10 F20000")
        e = ex("G92_ Z9.986", before)
        self.assertEqual(e.source, "community")
        self.assertIn("Z 9.986 mm", e.sentence)
        self.assertIn("0.014 mm", e.sentence)
        self.assertIn("believed", ex("M1006 Z9.99").sentence)

    def test_box_commands_are_community(self):
        for text in ("CUT_FILAMENT T=0", "TOOL_CHANGE_START F=0 T=1", "CLEAR_OOZE",
                     "BUFFER_MONITORING ENABLE=0", "UNLOAD_FILAMENT T=1"):
            self.assertEqual(ex(text).source, "community", text)
        self.assertIn("off for filament 1", ex("BOX_TEMP_SET VT0=0").sentence)

    def test_filament_slots(self):
        self.assertIn("filament 2 (T1)", ex("T1").sentence)
        self.assertIn("filament 4 (T3)", ex("UNLOAD_T3").sentence)
        self.assertEqual(ex("UNLOAD_T15").source, "vendor")

    def test_heater_command(self):
        self.assertIn("nozzle to 230 °C and wait",
                      ex("SET_HEATER_TEMPERATURE HEATER=extruder TARGET=230 WAIT=1").sentence)
        state = run("SET_HEATER_TEMPERATURE HEATER=extruder TARGET=230 WAIT=1")
        self.assertEqual(state.hotend_target, 230)

    def test_chamber_limits_explained(self):
        self.assertIn("65 °C", ex("M141 S50").details)

    def test_comment_markers(self):
        self.assertEqual(ex("; QIDIStudio 02.07.02.60").title, "Made by QIDIStudio 02.07.02.60")
        self.assertEqual(ex(";VT1 H-1").title, "Filament marker")
        self.assertIn("outside", ex("; FEATURE: Outer wall").sentence.lower())
        self.assertIn("outside", ex(";TYPE:Outer wall").sentence.lower())
        self.assertEqual(ex(";BEFORE_LAYER_CHANGE").title, "Before layer change")
        self.assertEqual(ex(";0.2").title, "Layer height marker")
        self.assertEqual(ex("; RU5ErkJggg==").title, "Preview image data")


if __name__ == "__main__":
    unittest.main()
