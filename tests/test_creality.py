import unittest
from pathlib import Path

from ventris.dialects import (creality, detect_profile, detection_sample, get_profile,
                              profiles)
from ventris.explain import explain
from ventris.parser import parse_line
from ventris.state import MachineState, StateTracker

FIXTURES = Path(__file__).parent / "fixtures"
SAMPLE = (FIXTURES / "k1max_cp4_sample.gcode").read_text(encoding="utf-8")


def ex(text, before=None):
    before = before or MachineState(fan_slots=creality.FAN_SLOTS)
    after = MachineState(**vars(before))
    line = parse_line(text)
    after.apply(line)
    return explain(line, before, after, get_profile("k1"))


def run(text):
    state = MachineState(fan_slots=creality.FAN_SLOTS)
    for line in text.splitlines():
        state.apply(parse_line(line))
    return state


class CrealityK1ProfileTest(unittest.TestCase):
    def test_registered(self):
        self.assertIn("k1", [p.key for p in profiles()])

    def test_detects_creality_print_4_file(self):
        self.assertEqual(detect_profile(detection_sample(SAMPLE)).key, "k1")

    def test_detects_header_behind_large_preview_images(self):
        # Creality Print 4 writes tens of KB of preview image before its header.
        image = "; " + "A" * 76 + "\n"
        body = "G1 X1 Y1 E.1\n" * 8000
        text = image * 600 + ";Machine Name:K1 Max\nSTART_PRINT EXTRUDER_TEMP=220\n" + body
        self.assertEqual(detect_profile(detection_sample(text)).key, "k1")

    def test_detects_orcaslicer_file(self):
        text = ("; generated by OrcaSlicer 2.1.0\nSTART_PRINT EXTRUDER_TEMP=250 BED_TEMP=80\n"
                "; printer_settings_id = Creality K1 (0.4 nozzle)\n")
        self.assertEqual(detect_profile(text).key, "k1")

    def test_every_command_in_sample_is_known(self):
        unknown = {parse_line(l).code for l in SAMPLE.splitlines()
                   if parse_line(l).code and ex(l).kind == "unknown"}
        self.assertEqual(unknown, set())

    def test_start_routine(self):
        e = ex("START_PRINT EXTRUDER_TEMP=220 BED_TEMP=50")
        self.assertEqual(e.source, "vendor")
        self.assertIn("nozzle to 220 °C", e.sentence)
        self.assertIn("bed to 50 °C", e.sentence)
        self.assertIn("priming line", e.sentence)
        state = run("START_PRINT EXTRUDER_TEMP=220 BED_TEMP=50")
        self.assertTrue(state.homed)
        self.assertEqual((state.hotend_target, state.bed_target), (220, 50))

    def test_fans_are_numbered_the_creality_way(self):
        self.assertIn("part-cooling", ex("M106 S255").sentence)
        self.assertIn("chamber fan", ex("M106 P1 S128").sentence)
        self.assertIn("side", ex("M106 P2 S255").sentence)
        self.assertIn("part-cooling fan and the auxiliary (side) fan", ex("M107").sentence)
        state = run("M106 S255\nM106 P1 S128\nM106 P2 S51")
        self.assertEqual((state.part_fan, state.chamber_fan, state.aux_fan), (100, 50, 20))

    def test_other_profiles_keep_bambu_fan_numbering(self):
        state = MachineState()
        state.apply(parse_line("M106 P1 S255"))
        self.assertEqual((state.part_fan, state.chamber_fan), (100, None))

    def test_tracker_uses_profile_fan_numbering(self):
        tracker = StateTracker(["M106 P1 S255"], fan_slots=creality.FAN_SLOTS)
        _, after = tracker.states_around(0)
        self.assertEqual((after.chamber_fan, after.part_fan), (100, None))

    def test_chamber_fan_target(self):
        self.assertIn("35 °C or cooler", ex("M141 S35").sentence)
        self.assertIn("off", ex("M141 S0").sentence)

    def test_corner_speed(self):
        self.assertIn("corner speed to 8 mm/s", ex("M205 X8").sentence)

    def test_cfs_tool_change_is_community(self):
        e = ex("T2")
        self.assertEqual(e.source, "community")
        self.assertIn("filament 3 (T2)", e.sentence)

    def test_cura_style_layers(self):
        state = run(SAMPLE)
        self.assertEqual((state.layer, state.total_layers), (2, 2))
        self.assertEqual(state.feature, "SKIN")

    def test_comment_markers(self):
        self.assertEqual(ex(";TYPE:WALL-OUTER").title, "Section: Outer wall")
        self.assertEqual(ex(";TYPE:FILL").title, "Section: Infill")
        self.assertEqual(ex(";LAYER:0").title, "Layer change")
        self.assertEqual(ex(";MESH:NONMESH").title, "Travel between objects")
        self.assertEqual(ex(";MESH:cube.stl").title, "Object: cube.stl")
        self.assertEqual(ex(";;retract;;").title, "Retraction note")
        self.assertEqual(ex(";Creality Print Version : V4.3.5.5641").title,
                         "Made by Creality Print V4.3.5.5641")
        self.assertEqual(ex(";----------Machine Config--------------").title, "Section label")
        self.assertEqual(ex(";Machine Name:K1 Max").title, "Slicer info: Machine Name")
        # Creality Print 5+ / OrcaSlicer markers come from the shared set
        self.assertEqual(ex(";TYPE:Outer wall").title, "Section: Outer wall")
        self.assertEqual(ex(";AFTER_LAYER_CHANGE").title, "After layer change")


if __name__ == "__main__":
    unittest.main()
